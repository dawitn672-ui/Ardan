// The far peoples' lore tables (990-far-peoples): node features/990-far-peoples/gen/gen.mjs [--check]
// Reads canon/lore/peoples-and-faiths.json (gitignored) and writes words.data.core.js: each far culture's three words
// (A.BIBLE_WORDS, for 47-realm-bible and 54-voices), its everyday food (A.FARP_FOOD), and each far faith's holy days
// as [name, month] (A.FARP_DAYS). Only names, numbers and short labels
// come from the lore; every sentence the game shows is written in the hand-made data files beside it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = path.dirname(fileURLToPath(import.meta.url)), root = path.join(dir, '../../..');
const P = JSON.parse(fs.readFileSync(path.join(root, 'canon/lore/peoples-and-faiths.json'), 'utf8'));
const MONTHS = ['january', 'february', 'march', 'april', 'may', 'june', 'july', 'august', 'september', 'october', 'november', 'december'];
const KEY = [[/new year|first week of the year|year's turn/, 0], [/midwinter|winter solstice|longest night/, 11], [/midsummer|summer solstice|longest day/, 5],
  [/spring equinox|vernal/, 2], [/autumn equinox/, 8], [/first snow|winter/, 10], [/spring|first foal|thaw|ice break/, 3], [/harvest|autumn/, 8],
  [/monsoon|the rains|rainy season/, 5], [/summer/, 6], [/dry season|after the rains/, 10]];
const clean = s => String(s).replace(/[<>"]/g, '').replace(/\s+/g, ' ').trim();
const short = (s, n) => { const w = clean(s).split(' '); return w.length > n ? w.slice(0, n).join(' ') : w.join(' '); };
const monthOf = s => {
  const t = String(s).toLowerCase();
  for (let i = 0; i < 12; i++) if (new RegExp('\\b' + MONTHS[i] + '\\b').test(t)) return i;
  const m = t.match(/(\d+)(st|nd|rd|th) (moon|month)/); if (m && +m[1] >= 1 && +m[1] <= 12) return +m[1] - 1;
  for (const [re, k] of KEY) if (re.test(t)) return k;
  return null;
};
const W = {}, FOOD = {}, DAYS = {}, RITES = {};
for (const c of P.cultures) {
  // a meaning is cut at its first colon or semicolon: "a tiger ridge: a clan's own hill" -> "a tiger ridge, a clan's own hill" stays short
  W[c.id] = c.words.slice(0, 3).map(w => [clean(w.word), short(String(w.meaning).replace(/;.*$/, ''), 10)]);
  FOOD[c.id] = short(c.food_short, 9);
}
for (const f of P.faiths) {
  const parts = String(f.festivals || '').split(/;\s*/).map(x => x.trim()).filter(Boolean);
  DAYS[f.religion_id] = parts.map(x => {
    const name = clean(x.split('(')[0].replace(/,? when .*$/, '').replace(/^and /, ''));
    return [short(name.replace(/^the /, 'the '), 7), monthOf(x)];
  }).filter(d => d[0]);
  RITES[f.religion_id] = String(f.rituals || '').split(/;\s*/).map(x => short(x.replace(/\(.*?\)/g, ''), 10)).filter(Boolean).slice(0, 5);
}
const js = `// Generated by gen/gen.mjs from the lore's peoples and faiths (990-far-peoples). Do not edit by hand.
// A.BIBLE_WORDS: each far culture's three words [word, meaning]. A.FARP_FOOD: its everyday food.
// A.FARP_DAYS: each far faith's holy days [name, month 0-11 or null when the lore gives no month].
(function () {
  const W = A.BIBLE_WORDS = A.BIBLE_WORDS || {};
  Object.assign(W, ${JSON.stringify(W)});
  A.FARP_FOOD = ${JSON.stringify(FOOD)};
  A.FARP_DAYS = ${JSON.stringify(DAYS)};
})();
`;
const out = path.join(dir, '../words.data.core.js');
if (process.argv.includes('--check')) { const ok = fs.existsSync(out) && fs.readFileSync(out, 'utf8') === js; console.log(ok ? 'words.data.core.js is current' : 'words.data.core.js is stale'); process.exit(ok ? 0 : 1); }
fs.writeFileSync(out, js);
console.log(`${Object.keys(W).length} cultures, ${Object.keys(DAYS).length} faiths, ${Object.values(DAYS).flat().length} holy days (${Object.values(DAYS).flat().filter(d => d[1] == null).length} without a month)`);
