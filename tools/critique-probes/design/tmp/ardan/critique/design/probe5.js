const { chromium } = require('/opt/node-tools/node_modules/playwright');
(async () => {
  const b = await chromium.launch();
  const page = await b.newPage({ viewport: { width: 1366, height: 900 }, deviceScaleFactor: 1 });
  const errs = [];
  page.on('pageerror', e => errs.push(String(e)));
  await page.goto('file:///tmp/ardan/snap/index.html');
  await page.waitForTimeout(2000);
  await page.click('[data-a="newLife"]');
  await page.waitForTimeout(800);
  await page.click('[data-a="crStep"][data-v="0"]');
  await page.waitForTimeout(500);
  await page.click('[data-a="crSet"][data-v="status:peasant"]');
  await page.click('[data-a="crSet"][data-v="startAge:0"]');
  await page.click('[data-a="crStep"][data-v="3"]');
  await page.fill('[data-c="crSeed"], #crSeed, input', '424242').catch(e=>console.log('fill fail', e.message));
  await page.click('[data-a="startLife"]');
  await page.waitForTimeout(2500);
  console.log(await page.evaluate(() => document.body.innerText.slice(0, 5000)));
  const btns = await page.evaluate(() => [...document.querySelectorAll('button,[data-a]')].slice(0, 150).map(b => b.tagName + '|' + (b.getAttribute('data-a') || '') + '|' + (b.getAttribute('data-v') || '') + '|' + (b.innerText||'').trim().replace(/\n/g,' / ').slice(0, 60)));
  console.log(btns.join('\n'));
  await page.screenshot({ path: 'L1-first-screen-1366.png', fullPage: false });
  const st = await page.evaluate(() => ({ seed: A.S.seed, year: A.S.year, pc: A.pc().name, age: A.pc().age, status: A.pc().status, ui: { screen: UI.screen, tab: UI.tab } }));
  console.log(JSON.stringify(st));
  console.log('ERRS', errs);
  await b.close();
})();
