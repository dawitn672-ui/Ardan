// Bundles Ardan v2's engine (the plain ES modules in src/<system>/engine/, entry src/core/engine/index.js) into one feature code file, so tools/build.mjs carries it into
// the single-page game like any other feature. The output is checked in; CI rebuilds it and fails if it differs.
//   node tools/build-v2.mjs            write src/core/99990-v2-engine/a-v2.core.js
//   node tools/build-v2.mjs --check    exit 1 if the checked-in bundle is stale
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src/core/99990-v2-engine/a-v2.core.js');
const r = await build({ entryPoints: [path.join(root, 'src/core/engine/index.js')], bundle: true, minify: false, format: 'iife', globalName: '__ARDAN_V2', write: false, target: 'es2020', legalComments: 'none', charset: 'utf8' });
const js = '// GENERATED by tools/build-v2.mjs from src/*/engine/*.js: do not edit; edit the engine modules and run node tools/build-v2.mjs\n' +
  r.outputFiles[0].text + 'A.V2 = __ARDAN_V2; if (typeof window !== "undefined") window.ARDAN_V2 = __ARDAN_V2;\n';
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== js) { console.error('src/core/99990-v2-engine/a-v2.core.js is stale: run node tools/build-v2.mjs'); process.exit(1); }
  console.log('v2 bundle up to date');
} else { fs.mkdirSync(path.dirname(out), { recursive: true }); fs.writeFileSync(out, js); console.log('v2 bundle', (js.length / 1024).toFixed(0), 'KB'); }
